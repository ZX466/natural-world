def willingness_expression(
    verdict: WillingnessVerdict, *, npc_name: str, action: str = ""
) -> WillingnessExpression | None:
    """verdict → 戏内表现（band 0 无表现=None；独白不嵌 NPC 名=第一人称铁律）。

    D10：模板从池中按 (band, npc_name) 确定性哈希选取——不同 npc 说法岔开
    （同输入恒同输出，C5）；`npc_name` 兼作选取键（仍不进文本）。

    **2026-11-02 修**：增 `action` 语境。给定动作**且有专属池** ⇒ 用专属池（选取键变
    `(npc_name, action)`，同人换动作换句）；无专属池（`move`/`build`）或 `action=""`
    ⇒ 池与选取键**一起**回落通用口径，**与修前逐位一致**（旧钉子不红）。

    ⚠️ 回落必须连键一起回落：只回落池、仍用 `(npc_name, action)` 作键，会让
    `move`/`build` 的独白静默换句（同人同档修前一句、修后另一句）——
    那不是「无专属池 ⇒ 行为不变」，而是未声明的行为变更。
    """
    if verdict.band <= 0:
        return None
    dedicated = _ACTION_TEMPLATES.get(action, {}).get(verdict.band)
    if dedicated is not None:
        pool: tuple[str, ...] = dedicated
        key = f"{npc_name}:{action}"
    else:
        pool = _TEMPLATES[verdict.band]
        key = npc_name
    idx = _pick_index(key, len(pool))
    template = pool[idx]
    return WillingnessExpression(
        band=verdict.band,
        monologue=template,
        defers=verdict.band >= 3,
    )


def _pick_index(key: str, pool_size: int) -> int:
    """key → 池内下标（sha256 截断取模；确定性，无 RNG 状态流）。"""
    digest = hashlib.sha256(key.encode("utf-8")).digest()
    return int.from_bytes(digest[0:4], "big") % pool_size


